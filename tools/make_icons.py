def used_names() -> list[str]:
    """出荷するアイコン名（ACTION_ICONS に現れるもの。パッケージが import できなければ全部）."""
    try:
        sys.path.insert(0, str(ROOT / "src"))
        from axicavity_fem.gui.ui.icon_set import ACTION_ICONS
        names = sorted(set(ACTION_ICONS.values()))
    except Exception:
        names = sorted(ICONS)
    missing = [n for n in names if n not in ICONS]
    if missing:
        raise SystemExit(f"ICONS に無いアイコン名: {missing}")
    return names


def write_icons(out: Path, names: list[str] | None = None) -> int:
    out.mkdir(parents=True, exist_ok=True)
    names = used_names() if names is None else names
    for stale in out.glob("*.svg"):
        if stale.stem not in names:
            stale.unlink()
    for name in names:
        (out / f"{name}.svg").write_text(HEAD.format(ink=INK) + ICONS[name].replace("\n", "") + "</svg>\n",
                                         encoding="utf-8", newline="\n")
    return len(names)


def write_sheet(src: Path, dst: Path, names: list[str]) -> None:
    """確認用の一覧（18 / 24 / 48 px と名前）."""
    from PySide6 import QtCore, QtGui, QtSvg, QtWidgets

    app = QtWidgets.QApplication.instance() or QtWidgets.QApplication(sys.argv[:1])   # noqa: F841
    cols, cell_w, cell_h = 8, 132, 96
    rows = (len(names) + cols - 1) // cols
    image = QtGui.QImage(cols * cell_w, rows * cell_h, QtGui.QImage.Format_ARGB32)
    image.fill(QtGui.QColor("#ffffff"))
    painter = QtGui.QPainter(image)
    painter.setRenderHint(QtGui.QPainter.Antialiasing)
    font = painter.font()
    font.setPointSize(8)
    painter.setFont(font)
    for k, name in enumerate(names):
        r, c = divmod(k, cols)
        x0, y0 = c * cell_w, r * cell_h
        renderer = QtSvg.QSvgRenderer(str(src / f"{name}.svg"))
        renderer.render(painter, QtCore.QRectF(x0 + 8, y0 + 10, 18, 18))
        renderer.render(painter, QtCore.QRectF(x0 + 8, y0 + 34, 24, 24))
        renderer.render(painter, QtCore.QRectF(x0 + 50, y0 + 8, 48, 48))
        painter.setPen(QtGui.QColor("#475569"))
        painter.drawText(QtCore.QRectF(x0, y0 + 66, cell_w, 20), QtCore.Qt.AlignCenter, name)
    painter.end()
    image.save(str(dst))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="リボンのアイコン（SVG）を書き出す")
    parser.add_argument("--out", type=Path, default=ICON_DIR, help="書き出し先（既定: gui/ui/icons）")
    parser.add_argument("--sheet", type=Path, help="確認用の一覧画像（PNG）も作る")
    args = parser.parse_args(argv)
    names = used_names()
    count = write_icons(args.out, names)
    print(f"{count} icons -> {args.out}")
    if args.sheet:
        write_sheet(args.out, args.sheet, names)
        print(f"sheet -> {args.sheet}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
