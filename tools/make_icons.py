def _hex_mesh(cx: float = 12.0, cy: float = 12.0, r: float = 9.0) -> str:
    """正六角形を正三角形 24 個に分けたメッシュ."""
    v = [(cx + r * math.cos(math.radians(60 * k)), cy + r * math.sin(math.radians(60 * k))) for k in range(6)]
    m = [((v[k][0] + v[(k + 1) % 6][0]) / 2, (v[k][1] + v[(k + 1) % 6][1]) / 2) for k in range(6)]

    def seg(a, b):
        return f"M{a[0]:.2f} {a[1]:.2f}L{b[0]:.2f} {b[1]:.2f}"
    inner = [seg(v[k], v[k + 3]) for k in range(3)]
    inner += [seg(m[(k + 3) % 6], m[(k + 5) % 6]) + seg(m[(k + 2) % 6], m[k]) for k in range(3)]
    outline = "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in v) + "z"
    return (f'<path d="{outline}" fill="{ACC_FILL}" stroke="none"/>'
            f'<path d="{"".join(inner)}" stroke="{ACC}" stroke-width="1.1"/>'
            f'<path d="{outline}" stroke-width="1.6"/>')


