JET_STOPS = ((0.0, "#1d4ed8"), (0.25, "#06b6d4"), (0.5, "#22c55e"), (0.75, "#facc15"), (1.0, "#dc2626"))


def _jet(t: float) -> str:
    t = min(1.0, max(0.0, t))
    for (t0, c0), (t1, c1) in zip(JET_STOPS, JET_STOPS[1:]):
        if t <= t1:
            f = (t - t0) / (t1 - t0)
            a = [int(c0[i:i + 2], 16) for i in (1, 3, 5)]
            b = [int(c1[i:i + 2], 16) for i in (1, 3, 5)]
            return "#" + "".join(f"{round(x + (y - x) * f):02x}" for x, y in zip(a, b))
    return JET_STOPS[-1][1]


def _gradient_cells(x0: float, y0: float, width: float, height: float, cols: int, rows: int) -> str:
    w, h = width / cols, height / rows
    return "".join(
        f'<rect x="{x0 + c * w:g}" y="{y0 + r * h:g}" width="{w:g}" height="{h:g}" '
        f'fill="{_jet((c + rows - 1 - r) / (cols + rows - 2))}" stroke="none"/>'
        for r in range(rows) for c in range(cols))


